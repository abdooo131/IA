/** Translates ledger memos (stored in English) for statements. Unknown text is shown as is. */
export function memoLabel(memo: string, t: Dict): string {
  const exact: Record<string, string> = {
    'COD collected': t.mCodCollected,
    'Shiply fees': t.mShiplyFees,
    'Failed delivery charge': t.mFailedCharge,
    Cashout: t.mCashout,
    'Cashout payment': t.mCashout,
    'Cashout fee': t.mCashoutFee,
    VAT: t.mVat,
    Shipping: t.mShipping,
    'COD fee': t.mCodFee,
    'Open package fee': t.mOpenFee,
  };
  if (exact[memo]) return exact[memo];
  for (const [prefix, label] of [['Compensation: ', t.mCompensation], ['Deduction: ', t.mDeduction], ['Reversal: ', t.mReversal]] as const) {
    if (memo.startsWith(prefix)) return `${label}: ${memoLabel(memo.slice(prefix.length), t)}`;
  }
  return memo;
}
