// Exports of a list's rows as CSV (house rules: UTF-8 byte order mark so Excel shows Arabic,
// cells starting with = + - @ prefixed with ' unless they are plain numbers) and as a minimal
// Excel workbook (.xlsx): one sheet, inline strings and numbers, stored (not compressed) in a
// zip written here, so neither the web nor the API needs a spreadsheet library.

export type ExportCell = string | number | null | undefined;

const csvCell = (value: ExportCell) => {
  const text = value === null || value === undefined ? '' : String(value);
  const safe = /^[=+\-@\t\r]/.test(text) && !/^-?\d+(\.\d+)?$/.test(text) ? `'${text}` : text;
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
};

/** A CSV for Excel: byte order mark, formulas neutralised, Windows line ends. */
export function exportCsv(header: string[], rows: ExportCell[][]): string {
  return `${String.fromCharCode(0xfeff)}${[header, ...rows].map((r) => r.map(csvCell).join(',')).join('\r\n')}\r\n`;
}

